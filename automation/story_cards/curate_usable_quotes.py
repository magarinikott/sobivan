def find_contiguous(lines: list[str], paragraphs: list[list[str]]) -> bool:
    target = [normalize(line) for line in lines]
    for paragraph in paragraphs:
        source = [normalize(line) for line in paragraph]
        for start in range(len(source) - len(target) + 1):
            if source[start : start + len(target)] == target:
                return True
    return False


def main() -> None:
    songs = parse_songs(REPO / "index.html")
    old_quotes = json.loads(OLD_BANK.read_text(encoding="utf-8"))["quotes"]
    old_ids = {
        (quote["song_id"], normalize(" ".join(quote["lines"]))): quote["id"]
        for quote in old_quotes
    }

    result: list[dict] = []
    seen: set[tuple[str, str]] = set()
    for song_id, blocks in CURATED.items():
        if song_id not in songs:
            raise RuntimeError(f"нет песни {song_id}")
        paragraphs = lyric_paragraphs(songs[song_id]["text"])
        for block in blocks:
            lines = block.splitlines()
            key_text = normalize(" ".join(lines))
            key = (song_id, key_text)
            if key in seen:
                raise RuntimeError(f"дубль: {song_id}: {block}")
            seen.add(key)
            if not find_contiguous(lines, paragraphs):
                raise RuntimeError(f"не найден цельный отрывок: {song_id}: {block}")
            quote_id = old_ids.get(key)
            if not quote_id:
                quote_id = f"{song_id}-usable-{hashlib.sha1(key_text.encode()).hexdigest()[:10]}"
            lowered = key_text.lower()
            result.append(
                {
                    "id": quote_id,
                    "song_id": song_id,
                    "song": songs[song_id]["title"],
                    "lines": lines,
                    "enabled": True,
                    "explicit": any(word in lowered for word in EXPLICIT_WORDS),
                    "political": song_id in POLITICAL_SONGS,
                    "review": "standalone_meaningful",
                }
            )

    payload = {
        "version": 2,
        "series": "Шум между строк",
        "review_criteria": [
            "Фраза понятна без соседних строк песни.",
            "В ней есть законченная мысль, образ, ирония или эмоциональный крючок.",
            "Её можно перепостить как самостоятельную карточку.",
            "Случайные обрывки, служебные строки и слабые дубли исключены.",
        ],
        "source_candidate_count": 2032,
        "usable_count": len(result),
        "quotes": result,
    }
    OUTPUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    markdown = [
        "# Банк отобранных цитат · «Шум между строк»",
        "",
        f"Из 2032 автоматических кандидатов отобрано **{len(result)}** самостоятельных фраз из всех 22 песен.",
        "",
        "Критерии: законченная мысль; понятность без контекста песни; образ, ирония или эмоциональный крючок; пригодность для отдельной story-карточки.",
        "",
        "Пометки `explicit` и `political` нужны не для цензуры, а чтобы в один пак не попадало сразу несколько таких фраз.",
        "",
    ]
    current_song = None
    number = 0
    for quote in result:
        if quote["song"] != current_song:
            current_song = quote["song"]
            number = 0
            markdown.extend([f"## {current_song}", ""])
        number += 1
        flags = []
        if quote["explicit"]:
            flags.append("explicit")
        if quote["political"]:
            flags.append("political")
        suffix = f" _({' / '.join(flags)})_" if flags else ""
        markdown.append(f"**{number}.**{suffix}")
        markdown.extend([f"> {line}  " for line in quote["lines"]])
        markdown.append("")
    MARKDOWN_OUTPUT.write_text("\n".join(markdown) + "\n", encoding="utf-8")
    print(f"{len(result)} осмысленных цитат -> {OUTPUT} и {MARKDOWN_OUTPUT}")


if __name__ == "__main__":
    main()
